void main() {
    /*
   char = letras
   String= palavras ou frases
   int = números inteiros até (2 bilhões)
   double = números decimais
   boolean = true ou false
   final = const. Não pode ser alterado e a palavra pode ser MAIUSCULA
   */

    char primeiraLetra = 'O';
    final String NOME = "Otávio"; // "final" não pode mudar o resultado, que é "Otávio".
    String sobrenome = "Lima";
    int idade = 18;
    double nota = 12.5;
    boolean aprovado = true;

    System.out.println(primeiraLetra);
    System.out.println(NOME);
    System.out.println(sobrenome);
    System.out.println(idade);
    System.out.println(nota);
    System.out.println(aprovado);

}
